/**
 * 템플릿을 채운다. `{자리}` 뒤에 조사가 붙어 있으면 받침을 보고 고른다.
 * "{자리}가 넓어지는" + "밀어붙이는 힘" → "밀어붙이는 힘이 넓어지는".
 */
export function fillLife(template: string, area: string, span: string): string {
  return template
    .replace(/\{자리\}(이|가)/g, () => area + iga(area))
    .replace(/\{자리\}(은|는)/g, () => area + eun(area))
    .replace(/\{자리\}(을|를)/g, () => area + eul(area))
    .replace(/\{자리\}(과|와)/g, () => area + gwa(area))
    .replace(/\{자리\}/g, area)
    .replace(/\{기간\}/g, span);
}
